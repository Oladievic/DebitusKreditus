ALTER TABLE audit ADD COLUMN context TEXT CHECK(context IS NULL OR json_valid(context));
CREATE TRIGGER audit_no_replace BEFORE INSERT ON audit WHEN EXISTS(SELECT 1 FROM audit WHERE id=NEW.id OR rowid=NEW.rowid) BEGIN
  SELECT RAISE(ABORT, 'AUDIT_APPEND_ONLY');
END;
CREATE TRIGGER audit_no_update BEFORE UPDATE ON audit BEGIN
  SELECT RAISE(ABORT, 'AUDIT_APPEND_ONLY');
END;
CREATE TRIGGER audit_no_delete BEFORE DELETE ON audit BEGIN
  SELECT RAISE(ABORT, 'AUDIT_APPEND_ONLY');
END;
